"""Reference SPICE netlist emitted straight from design.py (same device lines xschem writes)."""
import design

STD_PINS = {}
STD_ORDER = {  # subckt port order of sky130_fd_sc_hd cells
    'inv': ['A', 'VGND', 'VNB', 'VPB', 'VPWR', 'Y'],
    'buf': ['A', 'VGND', 'VNB', 'VPB', 'VPWR', 'X'],
    'nand2': ['A', 'B', 'VGND', 'VNB', 'VPB', 'VPWR', 'Y'],
    'nor2': ['A', 'B', 'VGND', 'VNB', 'VPB', 'VPWR', 'Y'],
    'nand3': ['A', 'B', 'C', 'VGND', 'VNB', 'VPB', 'VPWR', 'Y'],
    'a31oi': ['A1', 'A2', 'A3', 'B1', 'VGND', 'VNB', 'VPB', 'VPWR', 'Y'],
    'nor2b': ['A', 'B_N', 'VGND', 'VNB', 'VPB', 'VPWR', 'Y'],
    'dfrbp': ['CLK', 'D', 'RESET_B', 'VGND', 'VNB', 'VPB', 'VPWR', 'Q', 'Q_N'],
    'dfrtp': ['CLK', 'D', 'RESET_B', 'VGND', 'VNB', 'VPB', 'VPWR', 'Q'],
    'dfxtp': ['CLK', 'D', 'VGND', 'VNB', 'VPB', 'VPWR', 'Q'],
}


def fmt(v):
    return ('%g' % v)


def mos_line(i):
    k = i.kw
    W, L, nf = k['W'], k['L'], k['nf']
    c = i.conn
    ad = int((nf + 1) / 2) * W / nf * 0.29
    as_ = int((nf + 2) / 2) * W / nf * 0.29
    pd = 2 * int((nf + 1) / 2) * (W / nf + 0.29)
    ps = 2 * int((nf + 2) / 2) * (W / nf + 0.29)
    nr = 0.29 / W
    return ('X%s %s %s %s %s sky130_fd_pr__%s L=%s W=%s nf=%d ad=%s as=%s pd=%s ps=%s nrd=%s nrs=%s sa=0 sb=0 sd=0 mult=1 m=1'
            % (i.name, c['D'], c['G'], c['S'], c['B'], k['model'], fmt(L), fmt(W), nf, fmt(ad), fmt(as_), fmt(pd), fmt(ps), fmt(nr), fmt(nr)))


def inst_line(cells, i):
    c = i.conn
    if i.kind == 'mos':
        return mos_line(i)
    if i.kind == 'vpp':
        if 'floatm3' in design.P['UNITCAP']:      # shielded PDK cell: 4th terminal (m3 shield) tied to c0
            return 'X%s %s %s %s %s sky130_fd_pr__%s mult=%d m=%d' % (i.name, c['c0'], c['c1'], c['b'], c['c0'], design.P['UNITCAP'], i.kw['mult'], i.kw['mult'])
        return 'X%s %s %s %s sky130_fd_pr__%s mult=%d m=%d' % (i.name, c['c0'], c['c1'], c['b'], design.P['UNITCAP'], i.kw['mult'], i.kw['mult'])
    if i.kind == 'mim':
        return 'X%s %s %s sky130_fd_pr__cap_mim_m3_1 W=%s L=%s MF=1 m=1' % (i.name, c['c0'], c['c1'], fmt(i.kw['W']), fmt(i.kw['L']))
    if i.kind == 'std':
        cell = i.kw['cell']
        order = STD_ORDER[cell.split('_')[0]]
        full = dict(design.SC)
        full.update(c)
        return '%s %s sky130_fd_sc_hd__%s' % (i.name.lower() if i.name[0] in 'xX' else 'x' + i.name, ' '.join(full[p] for p in order), cell)
    if i.kind == 'sub':
        sub = cells[i.kw['cell']]
        return '%s %s %s' % (i.name if i.name[0] in 'xX' else 'x' + i.name, ' '.join(c[p[0]] for p in sub.pins), sub.name)
    raise ValueError(i.kind)


def subckt(cells, c):
    out = ['.subckt %s %s' % (c.name, ' '.join(p[0] for p in c.pins))]
    out += [inst_line(cells, i) for i in c.insts]
    out.append('.ends\n')
    return '\n'.join(out)


def std_used(cells):
    s = set()
    for c in cells.values():
        for i in c.insts:
            if i.kind == 'std':
                s.add(i.kw['cell'])
    return sorted(s)


def emit(cells, path):
    order = [n for n in cells if n != 'sar10_adc'] + ['sar10_adc']
    with open(path, 'w') as f:
        f.write('* sar10_adc reference netlist (generated by gen/netlist.py)\n')
        for n in order:
            f.write(subckt(cells, cells[n]) + '\n')


if __name__ == '__main__':
    import sys
    cells = design.build()
    emit(cells, sys.argv[1])
    print('std cells:', std_used(cells))
